// Regenerates src/tools/engines/subtitles-add/geist-coverage.ts from the Geist font's character map,
// so the burn-in planner knows exactly which letters libass can draw with the bundled font.
// Run after upgrading the `geist` package: node scripts/geist-coverage.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const b = readFileSync(join(root, "node_modules/geist/dist/fonts/geist-sans/Geist-Regular.ttf"));
const tables = b.readUInt16BE(4);
let cmap = 0;
for (let i = 0; i < tables; i++) {
  const o = 12 + i * 16;
  if (b.toString("ascii", o, o + 4) === "cmap") cmap = b.readUInt32BE(o + 8);
}
const cps = new Set();
const subtables = b.readUInt16BE(cmap + 2);
for (let i = 0; i < subtables; i++) {
  const off = cmap + b.readUInt32BE(cmap + 4 + i * 8 + 4);
  const format = b.readUInt16BE(off);
  if (format === 4) {
    const seg = b.readUInt16BE(off + 6) / 2;
    for (let s = 0; s < seg; s++) {
      const end = b.readUInt16BE(off + 14 + s * 2);
      const start = b.readUInt16BE(off + 16 + seg * 2 + s * 2);
      for (let c = start; c <= end && c < 0xffff; c++) cps.add(c);
    }
  } else if (format === 12) {
    const groups = b.readUInt32BE(off + 12);
    for (let s = 0; s < groups; s++) {
      const st = b.readUInt32BE(off + 16 + s * 12);
      const en = b.readUInt32BE(off + 20 + s * 12);
      for (let c = st; c <= en; c++) cps.add(c);
    }
  }
}
const sorted = [...cps].sort((x, y) => x - y);
const ranges = [];
for (const c of sorted) {
  const last = ranges[ranges.length - 1];
  if (last && c === last[1] + 1) last[1] = c;
  else ranges.push([c, c]);
}
const version = JSON.parse(
  readFileSync(join(root, "node_modules/geist/package.json"), "utf8"),
).version;
const body = ranges.map(([s, e]) => `[0x${s.toString(16)}, 0x${e.toString(16)}]`).join(", ");
writeFileSync(
  join(root, "src/tools/engines/subtitles-add/geist-coverage.ts"),
  `/**
 * Code points Geist Sans Regular (geist ${version}) has glyphs for, as inclusive ranges. Generated by
 * scripts/geist-coverage.mjs from the font's cmap table; do not edit by hand. ${sorted.length} code points.
 */
export const GEIST_RANGES: readonly (readonly [number, number])[] = [${body}];
`,
);
console.log(`geist-coverage: ${sorted.length} code points in ${ranges.length} ranges`);
